<?php
declare(strict_types=1);

/**
 * Shop assistant — the answering engine behind the chat widget.
 *
 * WHAT THIS IS, AND WHAT IT IS NOT
 *
 * This is not a language model. It matches a customer's question against a
 * set of intents and answers from the shop's OWN data: the FAQ and info
 * pages that are already written and already translated, the live pricing
 * engine, and the products table. That choice is deliberate and has one
 * decisive advantage for a print shop — it cannot invent a price. A bot that
 * confidently quotes "€9 each" on a garment that costs €23 does more damage
 * than no bot at all, and it is the single most likely failure mode of a
 * generic hosted chat widget dropped onto a store.
 *
 * It costs nothing to run, needs no API key, no third-party account, and
 * sends no customer data anywhere.
 *
 * UPGRADING TO CLAUDE LATER
 *
 * The seam is answer(): give it a question and a locale, get back an answer.
 * To make this conversational, implement a Claude-backed answer() that sends
 * buildKnowledgeContext() as the system prompt — that method already renders
 * the whole knowledge base, with live prices, as text. Keep the intent match
 * as the fallback for when the API is unreachable, so the widget degrades to
 * "still useful" rather than "broken".
 */
final class ShopAssistant
{
    /** Minimum keyword score before an intent is considered a match. */
    private const MATCH_THRESHOLD = 1;

    private ?PDO $db;
    private string $locale;

    /** The question currently being answered, for handlers that parse it. */
    private string $lastQuestion = '';

    public function __construct(?PDO $db = null, string $locale = 'en')
    {
        $this->db     = $db;
        $this->locale = $locale === 'el' ? 'el' : 'en';
    }

    /**
     * Answer one question.
     *
     * @return array{intent:string, text:string, links:array<int,array{label:string,href:string}>, suggestions:array<int,string>}
     */
    public function answer(string $question): array
    {
        $this->lastQuestion = $question;
        $q = self::normalise($question);

        if ($q === '') {
            return $this->reply('empty', t('assistant.fallback.empty', false));
        }

        // A price cue plus a quantity is unambiguous, and it has to be decided
        // BEFORE keyword scoring.
        //
        // "how much for 10 t-shirts" names a garment, so the products intent
        // matches 't shirt' and 'shirt' and outscores pricing's 'how much for'
        // on sheer keyword count — and the customer gets a catalogue listing
        // instead of the number they asked for. No amount of keyword tuning
        // fixes that cleanly, because both intents are genuinely present; what
        // settles it is that a quantity was given, which only makes sense as a
        // request for a quote.
        if (self::looksLikePriceQuestion($q) && self::extractQuantity($question) !== null) {
            $quote = $this->quoteFor($question);
            if ($quote !== null) {
                return $this->reply('pricing', $quote, [
                    ['label' => t('assistant.link.start_design', false), 'href' => '/shop/select_product'],
                ]);
            }
        }

        $best      = null;
        $bestScore = 0;
        foreach ($this->intents() as $name => $spec) {
            $score = $this->score($q, $spec['keywords']);
            if ($score > $bestScore) {
                $bestScore = $score;
                $best      = $name;
            }
        }

        if ($best === null || $bestScore < self::MATCH_THRESHOLD) {
            // Nothing matched. Two things happen here, in this order.
            //
            // First the question is logged. An unmatched question is the only
            // honest signal about what the intent list is missing, and it is
            // worth more than any amount of guessing at new keywords.
            self::logUnmatched($question);

            // Then, and only then, the LLM is asked. Putting it behind the
            // matcher rather than in front of it is the whole design:
            //   - the common questions never leave this server, so they are
            //     instant, free, and cannot be answered wrongly;
            //   - prices are never generated by a model, because the pricing
            //     intent always matches before this point is reached;
            //   - a free tier's rate limit is essentially unreachable, since
            //     only unusual questions get this far;
            //   - and if the provider is slow, throttled or gone, the shop
            //     simply behaves as it did before the API existed.
            $llm = $this->answerWithLlm($question);
            if ($llm !== null) {
                return $this->reply('llm', $llm, [
                    ['label' => t('assistant.link.contact', false), 'href' => '/contact'],
                ]);
            }

            return $this->reply('fallback', t('assistant.fallback.text', false), [
                ['label' => t('assistant.link.contact', false), 'href' => '/contact'],
                ['label' => t('assistant.link.faq', false),     'href' => '/faq'],
            ]);
        }

        $spec = $this->intents()[$best];
        return $this->reply($best, ($spec['answer'])(), $spec['links'] ?? []);
    }

