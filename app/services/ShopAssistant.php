    /** Lists the garment types actually marked active in the catalogue. */
    private function answerProducts(): string
    {
        $names = [];
        if ($this->db instanceof PDO) {
            try {
                $stmt = $this->db->query(
                    "SELECT name FROM products WHERE active = 1 ORDER BY base_price ASC LIMIT 12"
                );
                $names = array_column($stmt->fetchAll(), 'name');
            } catch (\PDOException $e) {
                // Fall through to the generic answer rather than failing the reply.
            }
        }

        if (!$names) {
            return t('assistant.answer.products_generic', false);
        }

        return I18n::t('assistant.answer.products', ['list' => implode(', ', $names)]);
    }

    /**
     * Reuses answers already written and translated for the FAQ and info
     * pages, so the bot and the pages can never drift apart. Those strings
     * contain markup (<a>, <strong>) which the widget renders as HTML — the
     * source is our own language file, not user input.
     */
    private function answerFromFaq(string ...$keys): string
    {
        $parts = [];
        foreach ($keys as $k) {
            $v = t($k, false);
            if ($v !== '' && $v !== $k) {
                $parts[] = $v;
            }
        }
        return $parts ? implode(' ', $parts) : t('assistant.fallback.text', false);
    }

    private function cheapestRetailPrice(): ?float
    {
        if (!$this->db instanceof PDO) {
            return null;
        }
        try {
            $stmt = $this->db->query("
                SELECT base_price, slug, name
                FROM products
                WHERE active = 1 AND base_price IS NOT NULL
                ORDER BY base_price ASC
                LIMIT 1
            ");
            $row = $stmt->fetch();
            if (!$row) {
                return null;
            }
            return Pricing::unitPrice(
                (float)$row['base_price'],
                Pricing::categoryFor($row['slug'] ?? '', $row['name'] ?? ''),
                1
            );
        } catch (\PDOException $e) {
            return null;
        }
    }

