    // Answer builders — anything factual is computed, never typed in
    // ------------------------------------------------------------------

    /**
     * The quantity ladder, computed from the SAME engine that charges the
     * customer. The saving depends only on the margin bands, not on what a
     * blank costs: price = cost / (1 - margin), so the cost cancels out of
     * price(100) / price(1). Rounded DOWN so the "up to" claim stays true.
     */
    private function answerPricing(string $question = ''): string
    {
        // A question with a number in it ("how much for 10 t-shirts") deserves
        // a real figure, not a paragraph about discounts. The figure comes
        // from the same Pricing engine that charges at checkout, so the
        // assistant and the cart can never disagree.
        $quote = $this->quoteFor($question);
        if ($quote !== null) {
            return $quote;
        }

        $best = 0.0;
        foreach (['tshirt', 'hoodie'] as $cat) {
            $m1   = Pricing::marginFor($cat, 1);
            $m100 = Pricing::marginFor($cat, 100);
            if ($m100 < 1.0) {
                $best = max($best, 1 - (1 - $m1) / (1 - $m100));
            }
        }
        $pct = (int)(floor($best * 20) * 5);

        $from = $this->cheapestRetailPrice();
        $fromText = $from !== null
            ? I18n::t('assistant.answer.pricing_from', ['price' => number_format($from, 2)])
            : '';

        return trim(I18n::t('assistant.answer.pricing', ['percent' => $pct]) . ' ' . $fromText);
    }

    /**
     * Does this question ask about money at all?
     *
     * Stems, not whole words, for the same reason the intent lists use them:
     * Greek inflects the ending, so "κοστίζει", "κοστίζουν" and "κόστος" all
     * have to be caught by "κοστ". "ποσο καν" covers both "πόσο κάνει" and
     * "πόσο κάνουν", which an exact-word list kept missing.
     */
    private static function looksLikePriceQuestion(string $normalised): bool
    {
        foreach ([
            'how much', 'price', 'prices', 'cost', 'costs', 'quote', 'charge',
            'τιμ', 'κοστ', 'ποσο καν', 'ποσο κοστ', 'ποσο ειναι', 'ποσο θα',
            'ποσο εχ', 'χρεων',
        ] as $cue) {
            if (str_contains($normalised, $cue)) {
                return true;
            }
        }
        return false;
    }

    /**
     * Turn "how much for 10 t-shirts" into a real, checkout-accurate quote.
     *
     * Returns null when the question has no quantity in it, in which case the
     * caller falls back to the general pricing answer.
     *
     * Every number here is computed by Pricing — the same class the cart uses.
     * Nothing about price is ever written by hand or produced by a model,
     * because a wrong quote in a chat window is a promise the shop then has to
     * either honour or explain away.
     */
    private function quoteFor(string $question): ?string
    {
        if (!$this->db instanceof PDO) {
            return null;
        }

        $qty = self::extractQuantity($question);
        if ($qty === null) {
            return null;
        }

        $product = $this->matchProduct($question);
        if ($product === null) {
            return null;
        }

        $cat   = Pricing::categoryFor($product['slug'] ?? '', $product['name'] ?? '');
        $unit  = Pricing::unitPrice((float)$product['base_price'], $cat, $qty);
        $total = round($unit * $qty, 2);

        $text = I18n::t('assistant.answer.quote', [
            'qty'     => $qty,
            'product' => $product['name'],
            'unit'    => number_format($unit, 2),
            'total'   => number_format($total, 2),
        ]);

        // The next volume break, found by asking Pricing where the margin
        // changes rather than hard-coding the bands here. Worth showing: it
        // is genuinely useful to the customer and it is the shop's best
        // argument for a bigger order.
        $next = self::nextPriceBreak($cat, $qty);
        if ($next !== null) {
            $nextUnit = Pricing::unitPrice((float)$product['base_price'], $cat, $next);
            if ($nextUnit < $unit) {
                $text .= ' ' . I18n::t('assistant.answer.quote_next', [
                    'qty'  => $next,
                    'unit' => number_format($nextUnit, 2),
                ]);
            }
        }

        return $text . ' ' . t('assistant.answer.quote_note', false);
    }

    /**
     * First plausible quantity in the question.
     *
     * Deliberately ignores numbers that are clearly not a quantity: a price
     * the customer quotes back ("is it 13.80 each?"), a size ("5XL"), and
     * anything over 10,000, which is past what this shop quotes online.
     */
    private static function extractQuantity(string $question): ?int
    {
        $q = ' ' . mb_strtolower($question, 'UTF-8') . ' ';

        // Drop decimals and size tokens before looking for a count.
        $q = preg_replace('/\d+[.,]\d+/u', ' ', $q) ?? $q;
        $q = preg_replace('/\b\d+\s*xl\b/u', ' ', $q) ?? $q;

        if (!preg_match_all('/\b(\d{1,5})\b/u', $q, $m)) {
            return null;
        }
        foreach ($m[1] as $raw) {
            $n = (int)$raw;
            if ($n >= 1 && $n <= 10000) {
                return $n;
            }
        }
        return null;
    }

    /**
     * Which garment the customer means.
     *
     * Matched against the real catalogue, so it can never quote something the
     * shop does not sell. The synonym table exists because customers do not
     * type product names: they write "μπλούζες", "φούτερ", "tees".
     *
     * @return array<string,mixed>|null
     */
    private function matchProduct(string $question): ?array
    {
        try {
            $rows = $this->db->query(
                "SELECT id, name, slug, base_price FROM products
                 WHERE active = 1 AND base_price IS NOT NULL
                 ORDER BY base_price ASC"
            )->fetchAll();
        } catch (\PDOException $e) {
            return null;
        }
        if (!$rows) {
            return null;
        }

        $q = self::normalise($question);

        // Longest patterns first: "long sleeve" must beat "sleeve", and
        // "female t-shirt" must beat "t-shirt".
        $synonyms = [
            'female polo'   => ['female polo', 'γυναικειο πολο'],
            'polo'          => ['polo', 'πολο'],
            'female v-neck' => ['female v neck', 'γυναικειο βε'],
            'v-neck'        => ['v neck', 'vneck', 'βε λαιμο', 'βι λαιμο'],
            'long sleeve'   => ['long sleeve', 'longsleeve', 'μακρυμανικ'],
            'female tank'   => ['female tank', 'γυναικειο αμανικ'],
            'tank'          => ['tank top', 'tank', 'αμανικ'],
            'hoodie'        => ['hoodie', 'hoody', 'φουτερ', 'κουκουλα'],
            'female'        => ['female', 'women', 'womens', 'γυναικει'],
            't-shirt'       => ['t shirt', 'tshirt', 'tee', 'tees', 'shirt',
                                'μπλουζ', 'μπλουζακ', 'κοντομανικ'],
        ];

        $wanted = null;
        foreach ($synonyms as $key => $patterns) {
            foreach ($patterns as $pat) {
                if (str_contains($q, $pat)) {
                    $wanted = $key;
                    break 2;
                }
            }
        }

        // A bare "how much for 10?" means the shop's entry-level garment,
        // which is what "prices start from" already advertises.
        if ($wanted === null) {
            return $rows[0];
        }

        $needles = [
            'female polo'   => ['female polo'],
            'polo'          => ['polo'],
            'female v-neck' => ['female v-neck'],
            'v-neck'        => ['v-neck'],
            'long sleeve'   => ['long sleeve'],
            'female tank'   => ['female tank'],
            'tank'          => ['tank'],
            'hoodie'        => ['hoodie'],
            'female'        => ['female t-shirt'],
            't-shirt'       => ['t-shirt'],
        ][$wanted] ?? [];

        foreach ($needles as $needle) {
            foreach ($rows as $row) {
                if (str_contains(mb_strtolower($row['name'], 'UTF-8'), $needle)) {
                    return $row;   // cheapest match, since rows are price-sorted
                }
            }
        }

        return $rows[0];
    }

    /**
     * The quantity at which the per-unit price next drops.
     *
     * Probes Pricing::marginFor rather than duplicating the band table, so
     * editing the tiers in one place stays enough.
     */
    private static function nextPriceBreak(string $category, int $qty): ?int
    {
        $current = Pricing::marginFor($category, $qty);
        for ($q = $qty + 1; $q <= 1000; $q++) {
            if (Pricing::marginFor($category, $q) !== $current) {
                return $q;
            }
        }
        return null;
    }

