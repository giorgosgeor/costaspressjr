    /**
     * Length-weighted, because Greek keywords have to be stems and stems
     * overlap. "τιμ" (price) is a substring of "τιμολόγιο" (invoice), which
     * belongs to a different intent; with a flat score both would tie at 1
     * and the winner would be whichever intent happened to be declared
     * first. Weighting by length lets the longer, more specific match win on
     * its own merits rather than on declaration order.
     *
     * @param array<int,string> $keywords
     */
    private function score(string $q, array $keywords): int
    {
        $score = 0;
        foreach ($keywords as $kw) {
            if ($kw !== '' && str_contains($q, $kw)) {
                $score += (int)ceil(mb_strlen($kw, 'UTF-8') / 4);
            }
        }
        return $score;
    }

    /**
     * Lower-case, strip Greek accents, collapse whitespace and punctuation.
     *
     * The accent stripping matters more than it looks: Greek customers type
     * both "τιμή" and "τιμη", and a keyword list written one way would miss
     * half of them. mb_* functions are used throughout because Greek is
     * multi-byte and strtolower() would mangle it.
     */
    private static function normalise(string $s): string
    {
        $s = mb_strtolower(trim($s), 'UTF-8');

        $accents = [
            'ά' => 'α', 'έ' => 'ε', 'ή' => 'η', 'ί' => 'ι', 'ό' => 'ο',
            'ύ' => 'υ', 'ώ' => 'ω', 'ϊ' => 'ι', 'ϋ' => 'υ', 'ΐ' => 'ι',
            'ΰ' => 'υ', 'ς' => 'σ',
            'á' => 'a', 'é' => 'e', 'í' => 'i', 'ó' => 'o', 'ú' => 'u',
        ];
        $s = strtr($s, $accents);

        // Punctuation to spaces so "price?" still matches "price".
        $s = preg_replace('/[^\p{L}\p{N}\s]+/u', ' ', $s) ?? $s;
        $s = preg_replace('/\s+/u', ' ', $s) ?? $s;

        return trim($s);
    }

    /** @param array<int,array{label:string,href:string}> $links */
    private function reply(string $intent, string $text, array $links = []): array
    {
        return [
            'intent'      => $intent,
            'text'        => $text,
            'links'       => $links,
            'suggestions' => $intent === 'fallback' ? $this->suggestions() : [],
        ];
    }

